        // [2026-03-09] --- m10.ngc Carousel 版（旋轉到目標刀位，依控制模式分流）---
        private string GenerateM10Carousel(MachineConfig config)
        {
            bool isServo = config.Atc.ControlMode == CarouselControlMode.Servo;
            int pockets = config.Atc.ToolCount;
            int doMotorFwd = config.Atc.DoMotorFwd;
            int doMotorRev = config.Atc.DoMotorRev;
            int diRotationIndex = config.Atc.DiRotationIndex;
            int sensorTimeout = config.Atc.SensorTimeout / 1000; // ms → s

            if (isServo)
            {
                // [2026-03-10] Servo 模式：讀取當前 analog-out-00，計算最短路徑旋轉
                return $@"(Generated by CncController — {DateTime.Now:yyyy-MM-dd HH:mm:ss})
(M10 — Rotate carousel to pocket P, SERVO mode — shortest path)
o<m10> sub

#<target_pocket> = #<p>
#<pockets> = {pockets}
o100 if [EXISTS[#<_ini[atc]pockets>]]
    #<pockets> = #<_ini[atc]pockets>
o100 endif

; 目標角度 (0~360)
#<target_base> = [[#<target_pocket> - 1] * [360.0 / #<pockets>]]
; 當前命令角度（M68 E0 最後送出的值）
#<current> = #<_hal[motion.analog-out-00]>
#<current_base> = [[#<current> + 36000] MOD 360.0]
; 差值 → 正規化到 -180~+180（最短路徑）
#<diff> = [#<target_base> - #<current_base>]
o110 if [#<diff> GT 180]
    #<diff> = [#<diff> - 360]
o110 endif
o120 if [#<diff> LT -180]
    #<diff> = [#<diff> + 360]
o120 endif
#<new_angle> = [#<current> + #<diff>]
#3990 = #<target_pocket>

(PRINT, M10 SERVO: pocket #<target_pocket> current #<current> diff #<diff> new #<new_angle>)
M68 E0 Q[#<new_angle>]
G4 P0.5

o<m10> endsub [1]

M2
";
            }
            else
            {
                // IO 模式：馬達正轉 + RotationIndex 計數到位
                return $@"(Generated by CncController — {DateTime.Now:yyyy-MM-dd HH:mm:ss})
(M10 — Rotate carousel to pocket P, IO mode)
o<m10> sub

#<target_pocket> = #<p>
#<pockets> = {pockets}
o100 if [EXISTS[#<_ini[atc]pockets>]]
    #<pockets> = #<_ini[atc]pockets>
o100 endif

#<current_pocket> = #3990
o110 if [#<current_pocket> EQ #<target_pocket>]
    (PRINT, M10 IO: already at pocket #<target_pocket>)
    o<m10> endsub [1]
    M2
o110 endif

; Calculate shortest rotation direction
#<fwd_steps> = [[#<target_pocket> - #<current_pocket> + #<pockets>] MOD #<pockets>]
#<rev_steps> = [[#<current_pocket> - #<target_pocket> + #<pockets>] MOD #<pockets>]

o120 if [#<fwd_steps> LE #<rev_steps>]
    ; Forward rotation
    #<steps> = #<fwd_steps>
    #<count> = 0
    o130 while [#<count> LT #<steps>]
        M64 P{doMotorFwd}
        M66 P{diRotationIndex} L1 Q{sensorTimeout}
        o131 if [#5399 EQ -1]
            M65 P{doMotorFwd}
            (abort, Failed to get rotation index - FWD timeout)
        o131 endif
        M65 P{doMotorFwd}
        G4 P0.1
        #<count> = [#<count> + 1]
    o130 endwhile
o120 else
    ; Reverse rotation
    #<steps> = #<rev_steps>
    #<count> = 0
    o140 while [#<count> LT #<steps>]
        M64 P{doMotorRev}
        M66 P{diRotationIndex} L1 Q{sensorTimeout}
        o141 if [#5399 EQ -1]
            M65 P{doMotorRev}
            (abort, Failed to get rotation index - REV timeout)
        o141 endif
        M65 P{doMotorRev}
        G4 P0.1
        #<count> = [#<count> + 1]
    o140 endwhile
o120 endif

#3990 = #<target_pocket>
(PRINT, M10 IO: arrived at pocket #<target_pocket>)

o<m10> endsub [1]

M2
";
            }
        }

