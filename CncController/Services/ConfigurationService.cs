        private string GenerateSimAtcHal(MachineConfig config)
        {
            var sb = new StringBuilder();
            sb.AppendLine($"# Generated by CncController — {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            sb.AppendLine("# ATC Simulation HAL (manual sensor trigger mode)");
            sb.AppendLine("# Frontend toggles DI signals via /v2/hal/setp endpoint");
            sb.AppendLine();

            // [2026-03-12] 建立每個 DI 的虛擬信號（預設 0 = 未觸發）
            var diMappings = new List<(int PWord, string Name, string Desc)>
            {
                (config.Atc.DiCarouselHome, "carousel-home-in", "刀盤歸位感測"),
                (config.Atc.DiCarouselOut, "carousel-out-in", "刀盤到位感測"),
