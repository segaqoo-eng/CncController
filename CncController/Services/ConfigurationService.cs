using CncController.Models;

namespace CncController.Services
{
    public class ConfigurationService
    {
        public static ConfigurationService Instance { get; } = new ConfigurationService();

        private readonly HttpClient _http;
        private const string ConfigFileName = "MachineConfig.json";
        private readonly JsonSerializerOptions _jsonOptions;

        // [2026-03-05] 探針模擬開關：true=開發測試（HAL comp 模擬）, false=實機（硬體 probe-in）
        // 出廠前手動改為 false
        public const bool IsProbeSimulation = true;

        // [2026-03-10] ATC 模擬開關：true=測試階段（跳過 sensor 等待，只送 DO）, false=正式環境（等 DI sensor 確認）
        // 影響：extendatc/retractatc/m13(IO模式) 等 NGC 巨集
        public const bool IsAtcSimulation = true;

        private ConfigurationService()
        {
            // [Item 11] 伺服器 URL 從 AppSettings 讀取，不再硬寫
            _http = new HttpClient { BaseAddress = new Uri(AppSettings.Instance.ServerUrl) };
            _jsonOptions = new JsonSerializerOptions { WriteIndented = true, PropertyNameCaseInsensitive = true };
        }

        public async Task<MachineConfig> LoadConfigAsync()
        {
            try
            {
                if (!File.Exists(ConfigFileName)) return new MachineConfig();
                string json = await File.ReadAllTextAsync(ConfigFileName);
                return JsonSerializer.Deserialize<MachineConfig>(json, _jsonOptions) ?? new MachineConfig();
            }
            catch (Exception ex)
            {
                AlarmService.Instance.AddLog("ERR", $"Config load failed: {ex.GetType().Name}: {ex.Message}");
                return new MachineConfig();
            }
        }

        public async Task SaveConfigAsync(MachineConfig config)
        {
            try
            {
                // 1. 儲存 JSON 設定檔
                string json = JsonSerializer.Serialize(config, _jsonOptions);
                await File.WriteAllTextAsync(ConfigFileName, json);

                // 2. 生成 LinuxCNC 所需檔案
                string iniContent = GenerateIni(config);
                string xmlContent = GenerateXml(config);
                string halContent = GenerateHal(config);
                string postGuiContent = GeneratePostGuiHal(config);
                // [2026-03-05] 探針模擬 HAL：僅模擬模式產出
                // [2026-03-05] 探針模擬 HAL：需要 config 判斷位置回饋訊號名稱
                string simProbeHalContent = IsProbeSimulation ? GenerateSimProbeHal(config) : null;
                // [2026-03-12] ATC 模擬 HAL：僅模擬模式產出（建立虛擬 DI 信號供手動切換）
                string simAtcHalContent = IsAtcSimulation ? GenerateSimAtcHal(config) : null;

                // [2026-03-09] ATC NGC 巨集：依 AtcType 動態生成 4 個類型相關檔案
                var atcNgcFiles = GenerateAtcNgc(config);

                var payload = new
                {
                    IniContent = iniContent,
                    HalContent = halContent,
                    XmlContent = xmlContent,
                    PostGuiContent = postGuiContent,
                    SimProbeHalContent = simProbeHalContent,
                    // [2026-03-12] ATC 模擬 HAL 內容
                    SimAtcHalContent = simAtcHalContent,
                    // [2026-03-09] NGC 巨集內容（Dictionary<檔名, 內容>）
                    NgcFiles = atcNgcFiles
                };

                // 3. 傳送至後端並重啟
                await _http.PostAsJsonAsync("/api/config/update", payload);
                await _http.PostAsync("/api/machine/restart", null);
            }
            catch (Exception ex)
            {
                // [安全] 改為寫入 AlarmService（跑馬燈可見），並重新拋出讓呼叫端知道部署失敗
                AlarmService.Instance.AddLog("ERR", $"SaveConfig failed: {ex.GetType().Name}: {ex.Message}");
                throw;
            }
        }

        // ========================================================================================
        // 1. 生成 INI
        // ========================================================================================
        private string GenerateIni(MachineConfig config)
        {
            var sb = new StringBuilder();
            int axesCount = config.Axes.Count;
            string coordinates = string.Join(" ", config.Axes.Select(a => a.AxisID));
            string geometry = string.Join("", config.Axes.Select(a => a.AxisID));

            // [2026-03-05] 生成時間戳記
            sb.AppendLine($"# Generated by CncController — {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            sb.AppendLine();
            sb.AppendLine("[EMC]");
            sb.AppendLine("VERSION = 1.1");
            sb.AppendLine("MACHINE = SGCAM_PB_ATC");
            sb.AppendLine("DEBUG = 0");
            sb.AppendLine();

            sb.AppendLine("[DISPLAY]");
            sb.AppendLine("DISPLAY = probe_basic");
            sb.AppendLine("OPEN_FILE = ~/linuxcnc/nc_files/probe_basic/examples/blank.ngc");
            sb.AppendLine("CONFIG_FILE = custom_config.yml");
            sb.AppendLine("CYCLE_TIME = 0.200");
            sb.AppendLine("POSITION_OFFSET = RELATIVE");
            sb.AppendLine("POSITION_FEEDBACK = ACTUAL");
            sb.AppendLine("MAX_FEED_OVERRIDE = 2.0");
            sb.AppendLine("MAX_SPINDLE_OVERRIDE = 2.0");
            sb.AppendLine("MIN_SPINDLE_OVERRIDE = 0.5");
            sb.AppendLine("DEFAULT_SPINDLE_SPEED = 300");
            sb.AppendLine("PROGRAM_PREFIX = ~/linuxcnc/nc_files");
            sb.AppendLine("INTRO_GRAPHIC = pbsplash.png");
            sb.AppendLine("INTRO_TIME = 3");
            sb.AppendLine("EDITOR = gedit");
            sb.AppendLine("INCREMENTS = JOG 0.1 0.01 0.001");
            sb.AppendLine($"GEOMETRY = {geometry}");
            sb.AppendLine($"DRO_DISPLAY = {geometry}");
            // [2026-03-03] 依啟用軸動態產生 OFFSET_COLUMNS，告訴 PB UI 表格顯示哪些軸
            sb.AppendLine($"OFFSET_COLUMNS = {coordinates}");
            // [2026-03-09] ATC_TAB_DISPLAY 依刀庫類型動態切換：None→0, Umbrella→1, Turret→2
            int atcTabDisplay = config.Atc.Type switch
            {
                AtcType.Umbrella => 1,
                AtcType.Turret => 2,
                _ => 0
            };
            sb.AppendLine($"ATC_TAB_DISPLAY = {atcTabDisplay}");
            sb.AppendLine("USER_BUTTONS_PATH = user_buttons/");
            sb.AppendLine("USER_ATC_BUTTONS_PATH = user_atc_buttons/");
            sb.AppendLine("USER_DROS_PATH = user_dro_display/");
            sb.AppendLine();

            sb.AppendLine("[FILTER]");
            sb.AppendLine("PROGRAM_EXTENSION = .nc,.txt,.tap Other NC files");
            sb.AppendLine("png = image-to-gcode");
            sb.AppendLine();

            sb.AppendLine("[PYTHON]");
            sb.AppendLine("TOPLEVEL = ./python/toplevel.py");
            sb.AppendLine("PATH_APPEND = ./python/");
            sb.AppendLine();

            // [2026-03-09] [ATC] 參數化：依 AtcConfig 動態生成
            sb.AppendLine("[ATC]");
            sb.AppendLine($"POCKETS = {config.Atc.ToolCount}");
            sb.AppendLine($"Z_TOOL_CHANGE_HEIGHT = {config.Atc.ZToolChangeHeight}");
            sb.AppendLine($"Z_TOOL_CLEARANCE_HEIGHT = {config.Atc.ZClearanceHeight}");
            // [2026-03-09] 刀盤控制模式：SERVO=伺服定角度 / IO=馬達+感測器計數
            sb.AppendLine($"CONTROL_MODE = {(config.Atc.ControlMode == CarouselControlMode.Servo ? "SERVO" : "IO")}");
            // [2026-03-09] Carousel Servo 參數（供 HAL 參考）
            if (config.Atc.ControlMode == CarouselControlMode.Servo && config.Atc.CarouselSlaveIndex >= 0)
            {
                sb.AppendLine($"CAROUSEL_SLAVE_INDEX = {config.Atc.CarouselSlaveIndex}");
                sb.AppendLine($"CAROUSEL_MAX_VEL = {config.Atc.CarouselMaxVel}");
                sb.AppendLine($"CAROUSEL_MAX_ACCEL = {config.Atc.CarouselMaxAccel}");
                sb.AppendLine($"CAROUSEL_PPR = {config.Atc.CarouselPulsePerRev}");
                sb.AppendLine($"CAROUSEL_PITCH = {config.Atc.CarouselPitch}");
            }
            if (config.Atc.Type == AtcType.Turret)
            {
                // Rack 專用參數（寫入 INI 供 NGC 讀取）
                sb.AppendLine($"RACK_TRAVERSE_SPEED = {config.Atc.RackTraverseSpeed}");
                sb.AppendLine($"RACK_POCKET_1_X = {config.Atc.RackPocket1X}");
                sb.AppendLine($"RACK_POCKET_1_Y = {config.Atc.RackPocket1Y}");
                sb.AppendLine($"RACK_POCKET_2_X = {config.Atc.RackPocket2X}");
                sb.AppendLine($"RACK_POCKET_2_Y = {config.Atc.RackPocket2Y}");
                sb.AppendLine($"RACK_CLEARANCE_X = {config.Atc.RackClearanceX}");
                sb.AppendLine($"RACK_CLEARANCE_Y = {config.Atc.RackClearanceY}");
            }
            sb.AppendLine();

            // [2026-03-05] 探針模擬設定（僅模擬模式產出）
            if (IsProbeSimulation)
            {
                sb.AppendLine("[PROBE]");
                sb.AppendLine("# Simulation mode — comp trigger positions managed by frontend");
                sb.AppendLine();
            }

            sb.AppendLine("[RS274NGC]");
            sb.AppendLine("RS274NGC_STARTUP_CODE = F10 S300 G21 G17 G40 G49 G54 G64 P0.001 G80 G90 G91.1 G92.1 G94 G97 G98");
            sb.AppendLine("PARAMETER_FILE = vmc_metric.var");
            sb.AppendLine("SUBROUTINE_PATH = macros_metric_sim");
            // [2026-03-09] REMAP：有刀庫時才啟用 M6/M10~M26 重映射
            if (config.Atc.Type != AtcType.None)
            {
                sb.AppendLine("REMAP=M6  modalgroup=6 prolog=change_prolog ngc=toolchange epilog=change_epilog");
                sb.AppendLine("REMAP=M10 modalgroup=6 argspec=P ngc=m10");
                sb.AppendLine("REMAP=M11 modalgroup=6 argspec=p ngc=m11");
                sb.AppendLine("REMAP=M12 modalgroup=6 argspec=p ngc=m12");
                sb.AppendLine("REMAP=M13 modalgroup=6 ngc=m13");
                sb.AppendLine("REMAP=M21 modalgroup=6 ngc=m21");
                sb.AppendLine("REMAP=M22 modalgroup=6 ngc=m22");
                sb.AppendLine("REMAP=M23 modalgroup=6 ngc=m23");
                sb.AppendLine("REMAP=M24 modalgroup=6 ngc=m24");
                sb.AppendLine("REMAP=M25 modalgroup=6 ngc=m25");
                sb.AppendLine("REMAP=M26 modalgroup=6 ngc=m26");
            }
            sb.AppendLine();

            sb.AppendLine("[EMCMOT]");
            sb.AppendLine("EMCMOT = motmod");
            sb.AppendLine("COMM_TIMEOUT = 1.0");
            sb.AppendLine("BASE_PERIOD = 100000");
            sb.AppendLine("SERVO_PERIOD = 1000000");
            // [2026-03-09] NUM_DIO：ATC 用 M64/M65/M66 需要足夠的 digital IO pin（預設僅 4 個）
            sb.AppendLine("NUM_DIO = 32");
            // [2026-03-09] NUM_AIO：Servo 模式刀盤用 M68 E0 Q[angle] 傳遞角度值
            sb.AppendLine("NUM_AIO = 4");
            sb.AppendLine();

            sb.AppendLine("[TASK]");
            sb.AppendLine("TASK = milltask");
            sb.AppendLine("CYCLE_TIME = 0.010");
            sb.AppendLine();

            sb.AppendLine("[HAL]");
            sb.AppendLine("HALUI = halui");
            sb.AppendLine("HALFILE = 3axis.hal");
            // [2026-03-05] 探針模擬模式：載入 sim_probe.hal（3 軸 comp + or3 自動觸發）
            if (IsProbeSimulation)
            {
                sb.AppendLine("HALFILE = sim_probe.hal");
            }
            // [2026-03-12] ATC 模擬 HAL：建立虛擬 DI 信號
            if (IsAtcSimulation)
            {
                sb.AppendLine("HALFILE = sim_atc.hal");
            }
            sb.AppendLine("POSTGUI_HALFILE = probe_basic_postgui.hal");
            sb.AppendLine();

            sb.AppendLine("[TRAJ]");
            sb.AppendLine($"AXES = {axesCount}");
            sb.AppendLine("SPINDLES = 1");
            sb.AppendLine($"COORDINATES = {coordinates}");
            sb.AppendLine("LINEAR_UNITS = mm");
            sb.AppendLine("ANGULAR_UNITS = degree");
            sb.AppendLine("DEFAULT_LINEAR_VELOCITY = 50");
            sb.AppendLine("MAX_LINEAR_VELOCITY = 125");
            sb.AppendLine();

            sb.AppendLine("[EMCIO]");
            sb.AppendLine("EMCIO = io");
            sb.AppendLine("CYCLE_TIME = 0.100");
            sb.AppendLine("TOOL_TABLE = tool_metric.tbl");
            sb.AppendLine("RANDOM_TOOLCHANGER = 0");
            sb.AppendLine();

            sb.AppendLine("[KINS]");
            sb.AppendLine($"JOINTS = {axesCount}");
            sb.AppendLine($"KINEMATICS = trivkins coordinates={geometry}");
            sb.AppendLine();

            sb.AppendLine("[SPINDLE]");
            // [2026-03-09] 主軸 EtherCAT Slave 站號（供後端讀取 encoder feedback）
            sb.AppendLine($"SLAVE_INDEX = {config.Spindle.SlaveIndex}");
            sb.AppendLine($"ENCODER_PPR = {config.Spindle.EncoderPPR}");
            sb.AppendLine("PGAIN_V = 0");
            sb.AppendLine("IGAIN_V = 0.01");
            sb.AppendLine("DGAIN_V = 0");
            sb.AppendLine("FF0_V = 1");
            sb.AppendLine("FF1_V = 0");
            sb.AppendLine("PGAIN_P = 100");
            sb.AppendLine("IGAIN_P = 1");
            sb.AppendLine("DGAIN_P = 0");
            sb.AppendLine("FF0_P = 0");
            sb.AppendLine("FF1_P = 1");
            sb.AppendLine();

            for (int i = 0; i < axesCount; i++)
            {
                var axis = config.Axes[i];
                string axisName = axis.AxisID.ToUpper();
                double pitch = axis.Pitch == 0 ? 5.0 : axis.Pitch;
                double scale = axis.PulsePerRev / pitch;

                sb.AppendLine($"# --- Axis {axisName} ---");
                sb.AppendLine($"[AXIS_{axisName}]");
                sb.AppendLine($"MIN_LIMIT = {axis.SoftLimitNeg}");
                sb.AppendLine($"MAX_LIMIT = {axis.SoftLimitPos}");
                sb.AppendLine($"MAX_VELOCITY = {axis.MaxVelocity}");
                sb.AppendLine($"MAX_ACCELERATION = {axis.MaxAcceleration}");
                sb.AppendLine();

                sb.AppendLine($"[JOINT_{i}]");
                sb.AppendLine("TYPE = LINEAR");
                sb.AppendLine("HOME = 0.0");
                sb.AppendLine($"MIN_LIMIT = {axis.SoftLimitNeg}");
                sb.AppendLine($"MAX_LIMIT = {axis.SoftLimitPos}");
                sb.AppendLine($"MAX_VELOCITY = {axis.MaxVelocity}");
                sb.AppendLine($"MAX_ACCELERATION = {axis.MaxAcceleration}");
                sb.AppendLine($"STEP_SCALE = {scale:0.0}");
                sb.AppendLine("FERROR = 50.0");
                sb.AppendLine("MIN_FERROR = 5.0");

                sb.AppendLine("P_GAIN = 1000");
                sb.AppendLine("I_GAIN = 0");
                sb.AppendLine("D_GAIN = 0");
                sb.AppendLine("FF0 = 0");
                sb.AppendLine("FF1 = 1.0");

                double searchVel = 0;
                double latchVel = 0;
                string useIndex = "NO";
                string ignoreLimits = "NO";

                switch (axis.HomingMode)
                {
                    case HomingMode.Immediate:
                        searchVel = 0; latchVel = 0; useIndex = "NO";
                        break;
                    case HomingMode.HomeSwitch:
                        searchVel = Math.Abs(axis.HomeSpeed) * axis.HomeDirection;
                        latchVel = Math.Abs(axis.HomeLatchSpeed) * axis.HomeDirection;
                        useIndex = axis.HomeUseIndex ? "YES" : "NO";
                        ignoreLimits = "YES";
                        break;
                    case HomingMode.LimitSwitch:
                        searchVel = Math.Abs(axis.HomeSpeed) * axis.HomeDirection;
                        latchVel = Math.Abs(axis.HomeLatchSpeed) * axis.HomeDirection;
                        useIndex = axis.HomeUseIndex ? "YES" : "NO";
                        ignoreLimits = "YES";
                        break;
                }

                sb.AppendLine($"HOME_OFFSET = {axis.HomeOffset}");
                sb.AppendLine($"HOME_SEARCH_VEL = {searchVel}");
                sb.AppendLine($"HOME_LATCH_VEL = {latchVel}");
                sb.AppendLine($"HOME_USE_INDEX = {useIndex}");
                sb.AppendLine($"HOME_IGNORE_LIMITS = {ignoreLimits}");
                sb.AppendLine($"HOME_SEQUENCE = {axis.HomeSequence}");
                sb.AppendLine();
            }
            return sb.ToString();
        }

        // ========================================================================================
        // 2. 生成 HAL (整合 IO Mappings 與標準訊號)
        // ========================================================================================
        private string GenerateHal(MachineConfig config)
        {
            var sb = new StringBuilder();
            int axesCount = config.Axes.Count;

            // [2026-03-05] 生成時間戳記
            sb.AppendLine($"# Generated by CncController — {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            sb.AppendLine();
            sb.AppendLine("loadrt [KINS]KINEMATICS");
            // [2026-03-09] num_dio=32：讓 motion module 建立 32 個 digital IO pin（供 ATC M64/M65/M66 使用）
            // [2026-03-09] num_aio：Servo 模式刀盤用 analog output 傳角度
            sb.AppendLine("loadrt [EMCMOT]EMCMOT servo_period_nsec=[EMCMOT]SERVO_PERIOD num_joints=[KINS]JOINTS num_dio=[EMCMOT]NUM_DIO num_aio=[EMCMOT]NUM_AIO");
            // [2026-03-09] Carousel Servo + Spindle Servo 需要額外 cia402 實例
            int cia402Count = axesCount;
            int carouselCia402Idx = -1;
            int spindleCia402Idx = -1;
            bool hasCarouselServo_pre = config.Atc.Type == AtcType.Umbrella
                                      && config.Atc.ControlMode == CarouselControlMode.Servo
                                      && config.Atc.CarouselSlaveIndex >= 0;
            bool hasSpindleServo = config.Spindle.SlaveIndex >= 0;
            if (hasSpindleServo)
            {
                spindleCia402Idx = cia402Count;
                cia402Count++;
            }
            if (hasCarouselServo_pre)
            {
                carouselCia402Idx = cia402Count;
                cia402Count++;
            }
            sb.AppendLine($"loadrt cia402 count={cia402Count}");

            var sliceNames = string.Join(",", config.Axes.Select(a => $"slice_{a.AxisID}"));
            var personalities = string.Join(",", Enumerable.Repeat("32", axesCount));
            sb.AppendLine($"loadrt bitslice names={sliceNames} personality={personalities}");

            // 計算 NOT 元件總需求
            int axisNotCount = axesCount * 3;
            int ioInvertCount = config.Mappings
                .Where(m => m.Type == MapType.Input || m.Type == MapType.Output)
                .SelectMany(m => m.Pins)
                .Count(p => p.IsInverted);

            int totalNotCount = axisNotCount + ioInvertCount;

            if (totalNotCount > 0) sb.AppendLine($"loadrt not count={totalNotCount}");

            // [2026-03-10] Spindle Servo：scale + conv-float-s32（float→s32 for target_velocity）+ ddt + near
            if (hasSpindleServo)
            {
                sb.AppendLine("loadrt scale count=2");          // scale.0=RPM→counts/s, scale.1=RPS→RPM
                sb.AppendLine("loadrt conv_float_s32 count=1"); // conv.0=float→s32 for EtherCAT target_velocity
                sb.AppendLine("loadrt ddt count=1");            // ddt.0=位置微分→速度回授
                sb.AppendLine("loadrt near");                   // at-speed 判斷
            }
            // [2026-03-09] Carousel Servo 模式：載入 limit3（加減速限制）
            bool hasCarouselServo = config.Atc.Type == AtcType.Umbrella
                                  && config.Atc.ControlMode == CarouselControlMode.Servo
                                  && config.Atc.CarouselSlaveIndex >= 0;
            if (hasCarouselServo)
            {
                sb.AppendLine("loadrt limit3 count=1");
            }

            sb.AppendLine("loadusr -W lcec_conf ethercat-conf.xml");
            sb.AppendLine("loadrt lcec");
            sb.AppendLine();

            sb.AppendLine("addf lcec.read-all servo-thread");
            foreach (var axis in config.Axes) sb.AppendLine($"addf slice_{axis.AxisID} servo-thread");
            for (int i = 0; i < axesCount; i++) sb.AppendLine($"addf cia402.{i}.read-all servo-thread");
            // [2026-03-09] Spindle cia402 read
            if (hasSpindleServo) sb.AppendLine($"addf cia402.{spindleCia402Idx}.read-all servo-thread");
            // [2026-03-09] Carousel cia402 read
            if (hasCarouselServo_pre) sb.AppendLine($"addf cia402.{carouselCia402Idx}.read-all servo-thread");

            if (totalNotCount > 0)
            {
                for (int k = 0; k < totalNotCount; k++) sb.AppendLine($"addf not.{k} servo-thread");
            }

            sb.AppendLine("addf motion-command-handler servo-thread");
            sb.AppendLine("addf motion-controller servo-thread");
            // [2026-03-10] Spindle scale + conv-float-s32 + ddt + near（在 motion 之後）
            if (hasSpindleServo)
            {
                sb.AppendLine("addf scale.0 servo-thread");
                sb.AppendLine("addf conv-float-s32.0 servo-thread");
                sb.AppendLine("addf scale.1 servo-thread");
                sb.AppendLine("addf ddt.0 servo-thread");
                sb.AppendLine("addf near.0 servo-thread");
            }
            // [2026-03-09] Carousel limit3（在 motion 之後、cia402 write 之前）
            if (hasCarouselServo)
            {
                sb.AppendLine("addf limit3.0 servo-thread");
            }
            for (int i = 0; i < axesCount; i++) sb.AppendLine($"addf cia402.{i}.write-all servo-thread");
            // [2026-03-09] Spindle cia402 write
            if (hasSpindleServo) sb.AppendLine($"addf cia402.{spindleCia402Idx}.write-all servo-thread");
            // [2026-03-09] Carousel cia402 write
            if (hasCarouselServo_pre) sb.AppendLine($"addf cia402.{carouselCia402Idx}.write-all servo-thread");
            sb.AppendLine("addf lcec.write-all servo-thread");
            sb.AppendLine();

            int currentNotIndex = 0;

            // =========================================================
            // A. 軸與馬達邏輯 (AXIS MAPPING)
            // =========================================================
            for (int i = 0; i < axesCount; i++)
            {
                var axis = config.Axes[i];
                string axisHalName = $"joint.{i}";

                // [2026-02-24] 修正：從 Mappings 動態取得 EtherCAT Slave Index，不再寫死 X→0, Y→2, Z→3
                // [2026-03-05] 修正：LogicalName 格式為 "X Axis"，需用 StartsWith 匹配 AxisID "X"
                string axName = axis.AxisID.ToUpper();
                var axisMapping = config.Mappings.FirstOrDefault(m =>
                    m.Type == MapType.Axis && m.LogicalName.StartsWith(axis.AxisID, StringComparison.OrdinalIgnoreCase));
                int sIdx;
                if (axisMapping != null)
                {
                    sIdx = axisMapping.PhysicalIndex;
                }
                else
                {
                    // 無映射時回退為 Joint Index（向後相容）
                    sIdx = axis.Index;
                    AlarmService.Instance.AddLog("WARN", $"No axis mapping found for {axis.AxisID}, fallback to slave index {sIdx}");
                }

                string sliceName = $"slice_{axis.AxisID}";

                // [2026-03-05] 重構：使用 ClassifyDevice() 統一設備類型判斷
                var map = config.Mappings.FirstOrDefault(m => m.PhysicalIndex == sIdx && m.Type == MapType.Axis)
                       ?? config.Mappings.FirstOrDefault(m => m.PhysicalIndex == sIdx);
                var deviceType = SlaveDeviceType.Unknown;
                // [2026-03-05] 傳入 DeviceCategory 優先用掃描結果判斷
                if (map != null) deviceType = ClassifyDevice(map.ExpectedVendorId, map.ExpectedProductCode, map.DeviceCategory);
                bool isServo = deviceType == SlaveDeviceType.Servo || deviceType == SlaveDeviceType.PulseGenerator;
                bool isPulseGen = deviceType == SlaveDeviceType.PulseGenerator;

                sb.AppendLine($"# --- Axis {axis.AxisID} (Slave {sIdx}) [Type: {(isServo ? "Servo" : "Stepper/OpenLoop")}] ---");

                sb.AppendLine($"net {axis.AxisID}-enable  {axisHalName}.amp-enable-out => cia402.{i}.enable");
                sb.AppendLine($"net {axis.AxisID}-control cia402.{i}.controlword => lcec.0.{sIdx}.control_word_J{sIdx}");
                sb.AppendLine($"net {axis.AxisID}-status  lcec.0.{sIdx}.status_word_J{sIdx} => cia402.{i}.statusword");

                sb.AppendLine($"setp cia402.{i}.csp-mode 1");

                // ★★★ [修正] 只有「不是」5621 才設定 Operation Mode ★★★
                if (isServo && !isPulseGen)
                {
                    sb.AppendLine($"setp lcec.0.{sIdx}.modes_of_operation_J{sIdx} 8");
                }

                sb.AppendLine($"setp cia402.{i}.pos-scale [JOINT_{i}]STEP_SCALE");

                sb.AppendLine($"net {axis.AxisID}-pos-cmd {axisHalName}.motor-pos-cmd => cia402.{i}.pos-cmd");
                sb.AppendLine($"net {axis.AxisID}-drv-target cia402.{i}.drv-target-position => lcec.0.{sIdx}.target_position_J{sIdx}");

                sb.AppendLine($"net {axis.AxisID}-pos-fb lcec.0.{sIdx}.position_actual_value_J{sIdx} => cia402.{i}.drv-actual-position");

                if (isServo && !isPulseGen)
                {
                    sb.AppendLine("# [Feedback] Real Encoder Feedback (Closed Loop)");
                    sb.AppendLine($"net {axis.AxisID}-pos-fb-final cia402.{i}.pos-fb => {axisHalName}.motor-pos-fb");
                }
                else
                {
                    sb.AppendLine("# [Feedback] Fake Feedback (Open Loop)");
                    sb.AppendLine($"net {axis.AxisID}-pos-cmd => {axisHalName}.motor-pos-fb");
                }

                sb.AppendLine($"net {axis.AxisID}-di-raw lcec.0.{sIdx}.digital_inputs_J{sIdx} => {sliceName}.in");

                // --- Homing & Limits Logic ---
                if (axis.HomingMode == HomingMode.Immediate)
                {
                    sb.AppendLine("# Homing: Immediate");
                }
                else if (axis.HomingMode == HomingMode.HomeSwitch)
                {
                    if (axis.HomeSwitchLogic != LimitLogic.NotUsed)
                    {
                        string rawHomeSig = $"{sliceName}.out-{axis.HomeDiIndex:00}";
                        if (axis.HomeSwitchLogic == LimitLogic.NC)
                        {
                            sb.AppendLine($"net {axis.AxisID}-home-raw {rawHomeSig} => not.{currentNotIndex}.in");
                            sb.AppendLine($"net {axis.AxisID}-home {axisHalName}.home-sw-in <= not.{currentNotIndex}.out");
                            currentNotIndex++;
                        }
                        else
                        {
                            sb.AppendLine($"net {axis.AxisID}-home {axisHalName}.home-sw-in <= {rawHomeSig}");
                        }
                    }
                }
                else if (axis.HomingMode == HomingMode.LimitSwitch)
                {
                    int targetDiIndex = (axis.HomeDirection > 0) ? axis.PosLimitDiIndex : axis.NegLimitDiIndex;
                    if (axis.LimitSwitchLogic != LimitLogic.NotUsed)
                    {
                        string rawSharedSig = $"{sliceName}.out-{targetDiIndex:00}";
                        if (axis.LimitSwitchLogic == LimitLogic.NC)
                        {
                            sb.AppendLine($"net {axis.AxisID}-home-shared-raw {rawSharedSig} => not.{currentNotIndex}.in");
                            sb.AppendLine($"net {axis.AxisID}-home {axisHalName}.home-sw-in <= not.{currentNotIndex}.out");
                            currentNotIndex++;
                        }
                        else
                        {
                            sb.AppendLine($"net {axis.AxisID}-home {axisHalName}.home-sw-in <= {rawSharedSig}");
                        }
                    }
                }

                if (axis.LimitSwitchLogic != LimitLogic.NotUsed)
                {
                    string rawNeg = $"{sliceName}.out-{axis.NegLimitDiIndex:00}";
                    if (axis.LimitSwitchLogic == LimitLogic.NC)
                    {
                        sb.AppendLine($"net {axis.AxisID}-neg-raw {rawNeg} => not.{currentNotIndex}.in");
                        sb.AppendLine($"net {axis.AxisID}-neg-lim {axisHalName}.neg-lim-sw-in <= not.{currentNotIndex}.out");
                        currentNotIndex++;
                    }
                    else
                    {
                        sb.AppendLine($"net {axis.AxisID}-neg-lim {axisHalName}.neg-lim-sw-in <= {rawNeg}");
                    }

                    string rawPos = $"{sliceName}.out-{axis.PosLimitDiIndex:00}";
                    if (axis.LimitSwitchLogic == LimitLogic.NC)
                    {
                        sb.AppendLine($"net {axis.AxisID}-pos-raw {rawPos} => not.{currentNotIndex}.in");
                        sb.AppendLine($"net {axis.AxisID}-pos-lim {axisHalName}.pos-lim-sw-in <= not.{currentNotIndex}.out");
                        currentNotIndex++;
                    }
                    else
                    {
                        sb.AppendLine($"net {axis.AxisID}-pos-lim {axisHalName}.pos-lim-sw-in <= {rawPos}");
                    }
                }
                sb.AppendLine();
            }

            // =========================================================
            // [2026-03-09] A2. Carousel Servo（Analog Output → limit3 → PID → EtherCAT）
            // =========================================================
            if (hasCarouselServo)
            {
                int cSlave = config.Atc.CarouselSlaveIndex;
                int cIdx = carouselCia402Idx; // cia402 instance index
                double cMaxVel = config.Atc.CarouselMaxVel;
                double cMaxAccel = config.Atc.CarouselMaxAccel;
                int cPPR = config.Atc.CarouselPulsePerRev;
                double cPitch = config.Atc.CarouselPitch > 0 ? config.Atc.CarouselPitch : 360.0;
                double cScale = (double)cPPR / cPitch;

                sb.AppendLine($"# --- Carousel Servo (Slave {cSlave}, cia402.{cIdx}, SERVO mode) ---");
                sb.AppendLine($"# SCALE = PPR/PITCH = {cPPR}/{cPitch} = {cScale:F4} pulses/deg");
                sb.AppendLine();

                // cia402 接線（EtherCAT ↔ cia402 driver）
                sb.AppendLine($"net carousel-enable   motion.motion-enabled       => cia402.{cIdx}.enable");
                sb.AppendLine($"net carousel-control  cia402.{cIdx}.controlword   => lcec.0.{cSlave}.control_word_J{cSlave}");
                sb.AppendLine($"net carousel-status   lcec.0.{cSlave}.status_word_J{cSlave} => cia402.{cIdx}.statusword");
                sb.AppendLine($"setp cia402.{cIdx}.csp-mode 1");
                sb.AppendLine($"setp lcec.0.{cSlave}.modes_of_operation_J{cSlave} 8");
                sb.AppendLine($"setp cia402.{cIdx}.pos-scale {cScale:F4}");
                sb.AppendLine();

                // limit3：加減速限制器
                sb.AppendLine($"setp limit3.0.maxv  {cMaxVel}");
                sb.AppendLine($"setp limit3.0.maxa  {cMaxAccel}");
                sb.AppendLine();

                // 信號鏈路：analog-out-00 → limit3(加減速) → cia402 → EtherCAT servo
                sb.AppendLine("# Signal chain: M68 E0 Q[angle] → limit3 → cia402 → EtherCAT");
                sb.AppendLine("net carousel-angle-raw   motion.analog-out-00      => limit3.0.in");
                sb.AppendLine($"net carousel-angle-cmd  limit3.0.out              => cia402.{cIdx}.pos-cmd");
                sb.AppendLine($"net carousel-drv-target cia402.{cIdx}.drv-target-position => lcec.0.{cSlave}.target_position_J{cSlave}");
                sb.AppendLine();

                // 位置回授：EtherCAT → cia402 → 閉環
                sb.AppendLine($"net carousel-pos-fb     lcec.0.{cSlave}.position_actual_value_J{cSlave} => cia402.{cIdx}.drv-actual-position");
                sb.AppendLine($"net carousel-pos-fb-enc cia402.{cIdx}.pos-fb");
                sb.AppendLine();
            }

            // =========================================================
            // [2026-03-09] A3. Spindle Servo（CiA 402 CSV 速度模式 + encoder 回讀）
            // =========================================================
            if (hasSpindleServo)
            {
                int sSlave = config.Spindle.SlaveIndex;
                int sIdx = spindleCia402Idx;
                int sPPR = config.Spindle.EncoderPPR;
                double sMaxRPM = config.Spindle.MaxRPM;

                sb.AppendLine($"# --- Spindle Servo (Slave {sSlave}, cia402.{sIdx}, CSV velocity mode) ---");
                sb.AppendLine();

                // [2026-03-09] cia402 接線（EtherCAT ↔ cia402 driver）
                sb.AppendLine($"net spindle-enable spindle.0.on            => cia402.{sIdx}.enable");
                sb.AppendLine($"net spindle-ctrl   cia402.{sIdx}.controlword => lcec.0.{sSlave}.control_word_J{sSlave}");
                sb.AppendLine($"net spindle-stat   lcec.0.{sSlave}.status_word_J{sSlave} => cia402.{sIdx}.statusword");
                // [2026-03-09] CSV 模式 (Cyclic Synchronous Velocity)：csp-mode=0, modes_of_operation=9
                sb.AppendLine($"setp cia402.{sIdx}.csp-mode 0");
                sb.AppendLine($"setp lcec.0.{sSlave}.modes_of_operation_J{sSlave} 9");
                sb.AppendLine($"setp cia402.{sIdx}.pos-scale {sPPR}");
                sb.AppendLine();

                // [2026-03-10] 速度命令：RPM → counts/s(float) → s32 → EtherCAT target_velocity
                // cia402 元件無 vel-cmd pin，CSV 模式速度命令必須直接送至 EtherCAT drive
                // target_velocity (0x60FF) 是 s32 型別，需經 conv-float-s32 轉換
                sb.AppendLine("# Speed command: RPM → counts/s → conv(float→s32) → EtherCAT target_velocity");
                sb.AppendLine($"setp scale.0.gain {(double)sPPR / 60.0:F6}");  // RPM × PPR/60 = counts/s
                sb.AppendLine("net spindle-rpm-cmd    spindle.0.speed-out      => scale.0.in");
                sb.AppendLine("net spindle-vel-float  scale.0.out              => conv-float-s32.0.in");
                sb.AppendLine($"net spindle-vel-target conv-float-s32.0.out    => lcec.0.{sSlave}.target_velocity_J{sSlave}");
                sb.AppendLine();

                // [2026-03-10] 位置回授：EtherCAT → cia402（encoder 換算）→ spindle.0.revs + ddt（速度回授）
                sb.AppendLine("# Position feedback: EtherCAT → cia402 (pos-scale) → spindle.0.revs");
                sb.AppendLine($"net spindle-pos-raw   lcec.0.{sSlave}.position_actual_value_J{sSlave} => cia402.{sIdx}.drv-actual-position");
                sb.AppendLine($"net spindle-revs      cia402.{sIdx}.pos-fb    => spindle.0.revs ddt.0.in");
                sb.AppendLine();

                // [2026-03-10] 速度回授：ddt(revs→RPS) → scale.1(×60→RPM) → spindle.0.speed-in
                sb.AppendLine("# Speed feedback: ddt(position→RPS) → RPM → spindle.0.speed-in");
                sb.AppendLine("setp scale.1.gain 60.0");  // RPS → RPM
                sb.AppendLine("net spindle-rps-fb    ddt.0.out               => scale.1.in");
                sb.AppendLine("net spindle-rpm-fb    scale.1.out             => spindle.0.speed-in");
                sb.AppendLine();

                // [2026-03-09] at-speed 判斷：|commanded - actual| < tolerance → spindle.0.at-speed
                sb.AppendLine("# At-speed detection");
                double tolerance = sMaxRPM * 0.02;  // 2% 容差
                sb.AppendLine($"setp near.0.difference {tolerance:F1}");
                sb.AppendLine("net spindle-rpm-cmd   => near.0.in1");
                sb.AppendLine("net spindle-rpm-fb    => near.0.in2");
                sb.AppendLine("net spindle-at-speed  near.0.out => spindle.0.at-speed");
                sb.AppendLine();
            }

            // =========================================================
            // ★★★ B. 標準系統訊號來源 (Standard Signals) ★★★
            // =========================================================
            sb.AppendLine("# === STANDARD SIGNALS (Source) ===");
            sb.AppendLine("net coolant-flood iocontrol.0.coolant-flood");
            sb.AppendLine("net coolant-mist  iocontrol.0.coolant-mist");
            // [2026-03-09] 主軸布林訊號（spindle-on 在 Servo 模式已由 cia402 enable 使用）
            if (!hasSpindleServo)
                sb.AppendLine("net spindle-on    spindle.0.on");
            sb.AppendLine("net spindle-cw    spindle.0.forward");
            sb.AppendLine("net spindle-ccw   spindle.0.reverse");
            sb.AppendLine("net spindle-brake spindle.0.brake");
            sb.AppendLine();

            // =========================================================
            // C. 通用 IO 邏輯 (IN/OUT MAPPINGS)
            // =========================================================
            sb.AppendLine("# === GENERAL IO MAPPINGS ===");

            // [2026-03-09] 收集 ATC 佔用的 pin，避免 GENERAL IO 重複接線
            var atcReservedDi = new HashSet<int>();
            var atcReservedDo = new HashSet<int>();
            int atcIoSlave = -1;
            if (config.Atc.Type != AtcType.None && config.Atc.IoSlaveIndex >= 0)
            {
                atcIoSlave = config.Atc.IoSlaveIndex;
                atcReservedDo.Add(config.Atc.DoCarouselOut);
                atcReservedDo.Add(config.Atc.DoCarouselHome);
                atcReservedDo.Add(config.Atc.DoDrawbar);
                atcReservedDo.Add(config.Atc.DoAirBlow);
                // [2026-03-09] Motor FWD/REV 僅 IO 模式佔用
                if (config.Atc.ControlMode == CarouselControlMode.IO)
                {
                    atcReservedDo.Add(config.Atc.DoMotorFwd);
                    atcReservedDo.Add(config.Atc.DoMotorRev);
                }
                atcReservedDi.Add(config.Atc.DiCarouselHome);
                atcReservedDi.Add(config.Atc.DiCarouselOut);
                atcReservedDi.Add(config.Atc.DiDrawbarClamp);
                atcReservedDi.Add(config.Atc.DiDrawbarUnclamp);
                // [2026-03-09] RotationIndex 僅 IO 模式佔用
                if (config.Atc.ControlMode == CarouselControlMode.IO)
                {
                    atcReservedDi.Add(config.Atc.DiRotationIndex);
                }
            }

            // 處理 INPUT
            foreach (var map in config.Mappings.Where(m => m.Type == MapType.Input))
            {
                string devicePrefix = $"lcec.0.{map.PhysicalIndex}";
                sb.AppendLine($"# Input Group {map.ChannelIndex} (Slave {map.PhysicalIndex})");

                foreach (var pin in map.Pins)
                {
                    // [2026-03-09] 跳過已被 ATC DI 佔用的 pin（同 Slave 時）
                    if (map.PhysicalIndex == atcIoSlave && atcReservedDi.Contains(pin.Index))
                    {
                        sb.AppendLine($"# [ATC] skipped din-{pin.Index:00} (reserved for ATC DI)");
                        continue;
                    }

                    string hwPin = $"{devicePrefix}.din-{pin.Index:00}";
                    string signalName = string.IsNullOrWhiteSpace(pin.Function)
                        ? $"input-G{map.ChannelIndex}-{pin.Index:00}"
                        : CleanSignalName(pin.Function);

                    // [2026-03-05] 模擬模式：跳過 probe-in 整條接線（由 sim_probe.hal 建立）
                    if (signalName == "probe-in" && IsProbeSimulation)
                    {
                        sb.AppendLine($"# [SIM] skipped: net {signalName} {hwPin} (handled by sim_probe.hal)");
                        continue;
                    }

                    if (pin.IsInverted)
                    {
                        sb.AppendLine($"net raw-{signalName} {hwPin} => not.{currentNotIndex}.in");
                        sb.AppendLine($"net {signalName} not.{currentNotIndex}.out");
                        currentNotIndex++;
                    }
                    else
                    {
                        sb.AppendLine($"net {signalName} {hwPin}");
                    }

                    // [2026-03-05] 實機模式：probe-in → motion.probe-input
                    if (signalName == "probe-in")
                    {
                        sb.AppendLine($"net {signalName} => motion.probe-input");
                    }
                }
                sb.AppendLine();
            }

            // 處理 OUTPUT
            foreach (var map in config.Mappings.Where(m => m.Type == MapType.Output))
            {
                string devicePrefix = $"lcec.0.{map.PhysicalIndex}";
                sb.AppendLine($"# Output Group {map.ChannelIndex} (Slave {map.PhysicalIndex})");

                foreach (var pin in map.Pins)
                {
                    // [2026-03-09] 跳過已被 ATC DO 佔用的 pin（同 Slave 時）
                    if (map.PhysicalIndex == atcIoSlave && atcReservedDo.Contains(pin.Index))
                    {
                        sb.AppendLine($"# [ATC] skipped dout-{pin.Index:00} (reserved for ATC DO)");
                        continue;
                    }

                    string hwPin = $"{devicePrefix}.dout-{pin.Index:00}";
                    string signalName = string.IsNullOrWhiteSpace(pin.Function)
                        ? $"output-G{map.ChannelIndex}-{pin.Index:00}"
                        : CleanSignalName(pin.Function);

                    if (pin.IsInverted)
                    {
                        sb.AppendLine($"net {signalName} => not.{currentNotIndex}.in");
                        sb.AppendLine($"net inv-{signalName} not.{currentNotIndex}.out => {hwPin}");
                        currentNotIndex++;
                    }
                    else
                    {
                        sb.AppendLine($"net {signalName} => {hwPin}");
                    }
                }
                sb.AppendLine();
            }

            // =========================================================
            // [2026-03-09] D. ATC IO 接線 (motion.digital-out/in ↔ EtherCAT IO)
            //   - 先檢查 ATC pin 與 GENERAL IO 是否衝突
            //   - 衝突 → 寫警告註解、跳過整段 ATC IO，不輸出
            // =========================================================
            if (config.Atc.Type != AtcType.None && config.Atc.IoSlaveIndex >= 0)
            {
                int ioSlave = config.Atc.IoSlaveIndex;

                // [2026-03-09] 收集 GENERAL IO 已佔用的 pin index（同 Slave、且有實際功能的 pin 才算）
                // 排除空白和預設佔位名（如 "Pin0"~"Pin31"）
                var generalDoPins = new HashSet<int>();
                var generalDiPins = new HashSet<int>();
                foreach (var map in config.Mappings.Where(m => m.Type == MapType.Output && m.PhysicalIndex == ioSlave))
                    foreach (var pin in map.Pins.Where(p => IsRealFunction(p.Function)))
                        generalDoPins.Add(pin.Index);
                foreach (var map in config.Mappings.Where(m => m.Type == MapType.Input && m.PhysicalIndex == ioSlave))
                    foreach (var pin in map.Pins.Where(p => IsRealFunction(p.Function)))
                        generalDiPins.Add(pin.Index);

                // [2026-03-09] 依控制模式動態組合 DO/DI 映射表
                var doMappings = new List<(int PWord, string Name)>
                {
                    (config.Atc.DoCarouselOut, "carousel-out"),
                    (config.Atc.DoCarouselHome, "carousel-home"),
                    (config.Atc.DoDrawbar, "drawbar"),
                    (config.Atc.DoAirBlow, "air-blow"),
                };
                // [2026-03-09] Motor FWD/REV 僅 IO 模式輸出
                if (config.Atc.ControlMode == CarouselControlMode.IO)
                {
                    doMappings.Add((config.Atc.DoMotorFwd, "motor-fwd"));
                    doMappings.Add((config.Atc.DoMotorRev, "motor-rev"));
                }
                var diMappings = new List<(int PWord, string Name)>
                {
                    (config.Atc.DiCarouselHome, "carousel-home-in"),
                    (config.Atc.DiCarouselOut, "carousel-out-in"),
                    (config.Atc.DiDrawbarClamp, "drawbar-clamp-in"),
                    (config.Atc.DiDrawbarUnclamp, "drawbar-unclamp-in"),
                };
                // [2026-03-09] RotationIndex 僅 IO 模式輸出
                if (config.Atc.ControlMode == CarouselControlMode.IO)
                {
                    diMappings.Add((config.Atc.DiRotationIndex, "rotation-index-in"));
                }

                // [2026-03-09] 衝突檢查：ATC DO/DI 是否與 GENERAL IO 用到相同 pin
                var conflicts = new List<string>();
                foreach (var (pWord, name) in doMappings)
                    if (generalDoPins.Contains(pWord))
                        conflicts.Add($"DO pin {pWord} (atc-{name}) conflicts with General IO output");
                foreach (var (pWord, name) in diMappings)
                    if (generalDiPins.Contains(pWord))
                        conflicts.Add($"DI pin {pWord} (atc-{name}) conflicts with General IO input");

                if (conflicts.Count > 0)
                {
                    // [2026-03-09] 有衝突：寫警告註解，不輸出 ATC IO 接線
                    sb.AppendLine("# === ATC IO WIRING — SKIPPED (PIN CONFLICT) ===");
                    sb.AppendLine($"# WARNING: ATC IO Slave {ioSlave} has {conflicts.Count} pin conflict(s):");
                    foreach (var c in conflicts)
                        sb.AppendLine($"#   - {c}");
                    sb.AppendLine("# Please reassign ATC IO pins in Settings → ATC IO to avoid overlap.");
                    sb.AppendLine();
                    // [2026-03-09] 同步記錄到 AlarmService 供 UI 跑馬燈顯示
                    AlarmService.Instance.AddLog("ERROR",
                        $"ATC IO 衝突：Slave {ioSlave} 有 {conflicts.Count} 個 pin 與通用 IO 重複，HAL 未輸出 ATC 接線。請至 ATC IO 設定調整 pin 編號。");
                }
                else
                {
                    // [2026-03-09] 無衝突：正常輸出 ATC IO 接線
                    sb.AppendLine("# === ATC IO WIRING ===");
                    foreach (var (pWord, name) in doMappings)
                        sb.AppendLine($"net atc-do-{name} motion.digital-out-{pWord:00} => lcec.0.{ioSlave}.dout-{pWord:00}");
                    // [2026-03-12] ATC 模擬模式：跳過 DI 硬體接線（由 sim_atc.hal 建立虛擬信號）
                    if (IsAtcSimulation)
                    {
                        foreach (var (pWord, name) in diMappings)
                            sb.AppendLine($"# [SIM] skipped: net atc-di-{name} lcec.0.{ioSlave}.din-{pWord:00} => motion.digital-in-{pWord:00}");
                    }
                    else
                    {
                        foreach (var (pWord, name) in diMappings)
                            sb.AppendLine($"net atc-di-{name} lcec.0.{ioSlave}.din-{pWord:00} => motion.digital-in-{pWord:00}");
                    }
                    sb.AppendLine();
                }
            }

            sb.AppendLine();
            sb.AppendLine("# --- SAFETY BYPASS (FORCE CONNECTION) ---");
            sb.AppendLine("unlinkp iocontrol.0.emc-enable-in");
            sb.AppendLine("net logic-enable iocontrol.0.user-enable-out => iocontrol.0.emc-enable-in");

            return sb.ToString();
        }

        // ========================================================================================
        // 3. 生成 XML (EtherCAT Topology - 修正混合模組與脈波模組)
        // ========================================================================================
        private string GenerateXml(MachineConfig config)
        {
            var sb = new StringBuilder();
            sb.AppendLine("<?xml version=\"1.0\" encoding=\"UTF-8\"?>");
            // [2026-03-05] 生成時間戳記
            sb.AppendLine($"<!-- Generated by CncController — {DateTime.Now:yyyy-MM-dd HH:mm:ss} -->");
            sb.AppendLine("<masters>");
            sb.AppendLine($"  <master idx=\"0\" appTimePeriod=\"1000000\" refClockSyncCycles=\"1000\">");

            int maxSlaveIndex = 0;
            if (config.Mappings.Any())
                maxSlaveIndex = config.Mappings.Max(m => m.PhysicalIndex);
            // [2026-03-09] Spindle/Carousel 伺服可能在 Mappings 之外，需納入 maxSlaveIndex 計算
            if (config.Spindle.SlaveIndex >= 0)
                maxSlaveIndex = Math.Max(maxSlaveIndex, config.Spindle.SlaveIndex);
            if (config.Atc.Type == AtcType.Umbrella && config.Atc.ControlMode == CarouselControlMode.Servo
                && config.Atc.CarouselSlaveIndex >= 0)
                maxSlaveIndex = Math.Max(maxSlaveIndex, config.Atc.CarouselSlaveIndex);
            if (maxSlaveIndex < 1) maxSlaveIndex = 1;

            for (int i = 0; i <= maxSlaveIndex; i++)
            {
                // 1. 找出這個 Slave Index 所有相關的設定 (可能同時有 IN 和 OUT)
                var slaveMappings = config.Mappings.Where(m => m.PhysicalIndex == i).ToList();

                // [2026-03-05] 修正：優先取 Axis mapping，確保 isServo 判斷正確（避免取到 IO mapping）
                var mainMap = slaveMappings.FirstOrDefault(m => m.Type == MapType.Axis)
                           ?? slaveMappings.FirstOrDefault();

                if (mainMap != null)
                {
