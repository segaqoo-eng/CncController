                    Models.DeviceCategory.DiDo     => SlaveDeviceType.IoModule,
                    Models.DeviceCategory.DigIn    => SlaveDeviceType.DigitalInput,
                    Models.DeviceCategory.DigOut   => SlaveDeviceType.DigitalOutput,
                    Models.DeviceCategory.Mpg      => SlaveDeviceType.Mpg,
                    Models.DeviceCategory.Coupler  => SlaveDeviceType.Coupler,
                    _                              => SlaveDeviceType.Unknown,
                };
            }

            // Fallback：用 VID/PID 字串比對（手動建立映射或舊設定檔相容）
            if (string.IsNullOrEmpty(pidStr)) return SlaveDeviceType.Unknown;
            string p = pidStr.ToLower().Trim().Replace("0x", "");
            string v = vidStr?.ToLower().Trim().Replace("0x", "") ?? "";

            // 匯川伺服
            if (p.Contains("c010d") || p.Contains("916")) return SlaveDeviceType.Servo;

            // 台達系列
            if (v.Contains("1dd"))
            {
                if (p.Contains("902"))  return SlaveDeviceType.IoModule;       // R2-EC0902
                if (p.Contains("5621")) return SlaveDeviceType.PulseGenerator; // 5621
                return SlaveDeviceType.Servo;                                   // 6080 等
            }

            return SlaveDeviceType.Unknown;
        }

        // [2026-03-09] 判斷 pin Function 是否為真正的功能（非空白、非預設佔位名 "Pin0"~"Pin31"）
        private static bool IsRealFunction(string function)
        {
            if (string.IsNullOrWhiteSpace(function)) return false;
            // [2026-03-09] 預設佔位名格式："Pin0", "Pin 0", "Pin 10", "Pin31" 等（不區分大小寫，中間可有空格）
            if (System.Text.RegularExpressions.Regex.IsMatch(function.Trim(), @"^Pin\s*\d+$", System.Text.RegularExpressions.RegexOptions.IgnoreCase))
                return false;
            return true;
        }

        private string CleanSignalName(string name)
        {
            if (string.IsNullOrEmpty(name)) return "unknown";
            char[] arr = name.ToCharArray();
            arr = Array.FindAll(arr, (c => (char.IsLetterOrDigit(c) || c == '_' || c == '-')));
            return new string(arr).Trim().Replace(" ", "-");
        }

